$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$envPath = Join-Path $projectRoot '.env'
if (Test-Path -LiteralPath $envPath) {
    throw '.env already exists; leaving it unchanged.'
}

function New-LocalSecret {
    $buffer = New-Object byte[] 32
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $generator.GetBytes($buffer) } finally { $generator.Dispose() }
    return ([BitConverter]::ToString($buffer)).Replace('-', '').ToLowerInvariant()
}

$content = Get-Content -LiteralPath (Join-Path $projectRoot '.env.example') -Raw
foreach ($key in @('MYSQL_PASSWORD', 'MYSQL_ROOT_PASSWORD', 'QDRANT_API_KEY', 'S3_ACCESS_KEY', 'S3_SECRET_KEY')) {
    $content = [regex]::Replace($content, "(?m)^${key}=CHANGE_ME\r?$", "${key}=$(New-LocalSecret)")
}
$content = $content.Replace('# Copy to .env; replace every CHANGE_ME before starting infrastructure.', '# Local development credentials generated by tools/init-env.ps1. Do not commit.')
$bytes = [System.Text.UTF8Encoding]::new($false).GetBytes($content)
$stream = [System.IO.File]::Open($envPath, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::Write)
try { $stream.Write($bytes, 0, $bytes.Length) } finally { $stream.Dispose() }
Write-Output 'Created .env with random local credentials; AI/WeChat credentials remain empty.'
